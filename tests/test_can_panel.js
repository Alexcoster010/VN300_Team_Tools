// Run with: node tests/test_can_panel.js
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const tree=require('../web/sensors.js');
const source=fs.readFileSync(require('node:path').join(__dirname,'../web/app.js'),'utf8');
new vm.Script(source);
const elements=new Map();
const get=id=>{if(!elements.has(id))elements.set(id,{textContent:'',value:'',hidden:false});return elements.get(id);};
let rendered;
const context=vm.createContext({Map,Number,JSON,page:'sensors',$:get,setTimeout:()=>{},SRTSensors:{...tree,createTree:()=>({render:nodes=>{rendered=nodes;},expandAll:()=>{},collapseAll:()=>{}})},api:async(_url,body)=>({scaling:{multiplier:body.multiplier,divider:body.divider}})});
const sensorStart=source.indexOf('let sensorPacket=null');
vm.runInContext(source.slice(sensorStart,source.indexOf('pollStorage();if',sensorStart)),context);
const flatten=nodes=>nodes.flatMap(n=>[n,...flatten(n.children||[])]);
const byId=id=>flatten(rendered).find(n=>n.id===id);
const snapshot={status:{enabled:true,capturing:true,frames:100,decoder:'MoTeC M1 reference'},evictions:0,bandwidth:{percent:12.3,bitrate:1000000,window_s:5,frames_per_s:100},frames:[{id:'0x640',extended:false,data:'03 E8',dlc:2,count:4,age_s:0.1}],signals:[{id:'0x640',name:'Engine › Speed',channel:'Engine_Speed',key:'rpm',value:6000,display_value:3000,raw:1000,age_s:0.1,unit:'rpm',message:'Engine',scaling:{multiplier:1,divider:2}},{id:'0x650',name:'Driver Switch',key:'switch',value:1,display_value:1,value_type:'boolean',raw:1,age_s:3,scaling:{multiplier:1,divider:1}},{id:'0x641',name:'Fuel Volume',key:'volume',value:1e-9,display_value:1e-9,raw:1,age_s:0.1,scaling:{multiplier:1,divider:1}}]};
context.input=snapshot;
vm.runInContext('canSnapshot=input;renderCan()',context);
assert.equal(byId('can-bus/bandwidth').value,'12.3');
assert.equal(byId('can/signal/rpm/display').value,'3000');
assert.equal(byId('can/signal/switch/display').value,'On');
assert.equal(byId('can/signal/volume/display').value,'1.0000e-9');
assert.equal(byId('can/signal/switch').stale,true);
assert.equal(byId('can/frame/0x640/false/data').value,'03 E8');
assert.match(byId('can-bus/health').note,/big-endian/);
// Drafts survive polling; scaling saves retain original raw and decoded values.
context.form={dataset:{key:'rpm'},elements:{multiplier:{value:'10'},divider:{value:'6'}},querySelector:()=>({disabled:false})};
context.event={target:{closest:()=>context.form},preventDefault:()=>{}};
get('sensorTree').oninput(context.event);
vm.runInContext('renderCan()',context);
assert.equal(byId('can/signal/rpm/scaling').editor.multiplier,'10');
get('sensorSearch').value='volume';vm.runInContext('refreshSensorTree()',context);
assert.equal(byId('can/signal/rpm'),undefined);
assert.ok(byId('can/signal/volume'));
get('sensorSearch').value='';
(async()=>{
 await get('sensorTree').onsubmit(context.event);
 assert.equal(snapshot.signals[0].display_value,10000);
 assert.equal(snapshot.signals[0].value,6000);
 assert.equal(snapshot.signals[0].raw,1000);
 assert.equal(byId('can/signal/rpm/scaling').editor.multiplier,10);
 assert.match(get('canScalingStatus').textContent,/saved/);
 context.form.elements.divider.value='0';await get('sensorTree').onsubmit(context.event);
 assert.match(get('canScalingStatus').textContent,/cannot be zero/);
 snapshot.bandwidth={reason:'Set the actual CAN bitrate in Setup',percent:null};vm.runInContext('renderCan()',context);
 assert.equal(byId('can-bus/bandwidth').value,'—');assert.match(byId('can-bus/bandwidth').note,/bitrate/);
 vm.runInContext('canOffline=true;renderCan()',context);
 assert.equal(byId('can-bus').status,'Connection unavailable');assert.equal(byId('can/signal/rpm').stale,true);
 console.log('CAN tree display, filtering, editing, raw frames, and bandwidth checks passed');
})().catch(err=>{console.error(err);process.exitCode=1;});
